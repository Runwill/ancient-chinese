def get_app_dir():
    """Directory that owns user data beside the source tree or executable."""
    configured = os.environ.get('HAN_NOCM_DATA_DIR', '').strip()
    if configured:
        return os.path.abspath(configured)
    if getattr(sys, 'frozen', False):
        return os.path.dirname(sys.executable)
    return os.path.dirname(os.path.abspath(__file__))


def version_tuple(value):
    """Return a comparable numeric tuple for a semantic-ish version string."""
    value = str(value or '').strip().lstrip('vV')
    numbers = []
    for part in value.split('.')[:3]:
        digits = ''.join(ch for ch in part if ch.isdigit())
        numbers.append(int(digits or 0))
    while len(numbers) < 3:
        numbers.append(0)
    return tuple(numbers)
